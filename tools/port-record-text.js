// Copies the journal page's report builder (buildEmailBody in index.html) into the backend as
// apps-script/09_RecordText.gs, so the server can write the same full report and send the same
// office email when the page closes before it could (see 10_Records.gs).
//   node tools/port-record-text.js      (run again whenever buildEmailBody changes)
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');

function block(startRe) {
  const m = src.match(startRe);
  if (!m) throw new Error('not found: ' + startRe);
  let i = src.indexOf('{', m.index), depth = 0, j = i;
  for (; j < src.length; j++) {
    const c = src[j];
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) break; }
  }
  return src.slice(m.index, j + 1);
}

const fn = block(/^function buildEmailBody\(result, p1, p2, p3\) /m)
  .replace(/^function buildEmailBody\(result, p1, p2, p3\) /, 'function buildRecordText_(S, result, p1, p2, p3) ');
const out = [
  '/**',
  ' * Trail Journal -- Apps Script backend',
  ' * File 9: the full written report, server-side. GENERATED by tools/port-record-text.js from',
  ' * buildEmailBody() in index.html -- do not edit here; edit the page and run the tool again.',
  ' * S = the journal fields the page keeps in its S object (see recordState_ in 10_Records.gs).',
  ' */',
  '',
  block(/^const LOCATION_TIER_ = /m) + ';',
  block(/^const CM_REASON_TIER_ = /m) + ';',
  "const CM_REASON_REQUIRES_EFFORT_ = 'ISS';",
  '',
  fn,
  '',
].join('\n');
fs.writeFileSync(path.join(__dirname, '..', 'apps-script', '09_RecordText.gs'), out);
console.log('09_RecordText.gs: ' + out.split('\n').length + ' lines');
